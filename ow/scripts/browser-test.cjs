// Run with Electron: electron ow/scripts/browser-test.cjs
// Starts its own OW server/save and never touches the player's profiles.
const {app,BrowserWindow}=require('electron');
const {spawn}=require('node:child_process');
const fs=require('node:fs/promises');
const path=require('node:path');
const assert=require('node:assert/strict');
const root=path.resolve(__dirname,'../..');
const ow=path.join(root,'ow');
let server;
const sleep=ms=>new Promise(r=>setTimeout(r,ms));
app.whenReady().then(async()=>{
  const entry=(await fs.readFile(path.join(ow,'src/main_ui.ow'),'utf8')).replace('"full/GameView.ow"','"../src/full/GameView.ow"').replace('"save/profiles.json"',`"generated/browser-save-${Date.now()}.json"`);
  await fs.writeFile(path.join(ow,'generated/browser-main.ow'),entry);
  server=spawn('java',['-Dow.web.port=0','-Dow.web.noBrowser=true','-jar',process.env.OW_JAR||path.join(root,'.packaging/ow-dictionaries/target/OwIDE.jar'),'run','generated/browser-main.ow'],{cwd:ow,windowsHide:true});
  let output='';
  const url=await new Promise((resolve,reject)=>{
    const timeout=setTimeout(()=>reject(new Error('OW server startup timeout: '+output)),15000);
    server.stdout.on('data',chunk=>{output+=chunk;const match=output.match(/http:\/\/127\.0\.0\.1:\d+\//);if(match){clearTimeout(timeout);resolve(match[0]);}});
    server.stderr.on('data',chunk=>{output+=chunk;});
    server.on('exit',code=>{if(code){clearTimeout(timeout);reject(new Error(output));}});
  });
  const win=new BrowserWindow({width:1440,height:1000,show:true,webPreferences:{backgroundThrottling:false,partition:'ow-test-'+Date.now()}});
  const js=code=>Promise.race([win.webContents.executeJavaScript(code),sleep(15000).then(()=>{throw new Error('Browser operation timed out: '+code);})]);
  const waitFor=async(code)=>{for(let i=0;i<100;i++){if(await js(code))return;await sleep(100);}throw new Error('Timed out: '+code);};
  const click=async(selector)=>{
    await waitFor(`document.getElementById('game').dataset.busy==='false'`);
    const rev=await js(`Number(document.getElementById('game').dataset.revision)`);
    assert(await js(`Boolean(document.querySelector(${JSON.stringify(selector)}))`),selector);
    await js(`document.querySelector(${JSON.stringify(selector)}).scrollIntoView({block:'nearest'})`);
    const point=await js(`(()=>{const e=document.querySelector(${JSON.stringify(selector)}),r=e.getBoundingClientRect();const x=r.x+r.width/2,y=r.y+r.height/2,t=document.elementFromPoint(x,y);return {x,y,reachable:t===e||e.contains(t)};})()`);
    assert(point.reachable,'Control obscured: '+selector);
    win.webContents.sendInputEvent({type:'mouseDown',x:Math.round(point.x),y:Math.round(point.y),button:'left',clickCount:1});
    win.webContents.sendInputEvent({type:'mouseUp',x:Math.round(point.x),y:Math.round(point.y),button:'left',clickCount:1});
    await waitFor(`Number(document.getElementById('game').dataset.revision)>${rev} && document.getElementById('game').dataset.busy==='false'`);
    await sleep(150);
  };
  const submit=async(action,value)=>{
    await waitFor(`document.getElementById('game').dataset.busy==='false'`);
    const rev=await js(`Number(document.getElementById('game').dataset.revision)`);
    await js(`(()=>{const f=document.querySelector('form[data-action="${action}"]');f.elements.value.value=${JSON.stringify(value)};f.requestSubmit();})()`);
    await waitFor(`Number(document.getElementById('game').dataset.revision)>${rev} && document.getElementById('game').dataset.busy==='false'`);
    await sleep(150);
  };
  const snapshots=[];
  const snapshot=async(name)=>{
    await sleep(500);
    await fs.writeFile(path.join(ow,'generated',name+'.png'),(await win.webContents.capturePage()).toPNG());
    const broken=await js(`[...document.images].filter(i=>!i.complete||!i.naturalWidth).map(i=>i.src)`);
    assert.deepEqual(broken,[],name+' broken images');snapshots.push(name);
  };
  await win.loadURL(url);
  await waitFor(`document.querySelectorAll('.skill-card').length===5`);
  await sleep(1000);
  await snapshot('menu');
  await click('[data-action="begin"]');
  const word=await js(`document.querySelector('[data-question]').textContent`);
  await submit('answer',word);
  assert.match(await js(`document.querySelector('.battling .meter-label').textContent`),/48\/60/);
  await snapshot('reading');
  await click('.exit-battle');
  await click('[data-action="navigate"][data-value="1"]');
  await click('[data-action="begin"]');
  const q=await js(`document.querySelector('[data-question]').textContent`);
  const m=q.match(/(\d+) \+ (\d+)/);assert(m,q);
  await submit('answer',String(Number(m[1])+Number(m[2])));
  assert.match(await js(`document.querySelector('.battling .meter-label').textContent`),/48\/60/);
  await snapshot('math');
  await click('.exit-battle');
  await click('[data-action="navigate"][data-value="1"]');
  await click('[data-action="begin"]');
  await snapshot('writing');
  await click('.exit-battle');
  await click('[data-action="navigate"][data-value="1"]');
  await click('[data-action="begin"]');
  await click('[data-action="clean"]');
  await submit('verify','FLOPPY DISK');
  assert.match(await js(`document.querySelector('.battling .card-title').textContent`),/Lvl 2/);
  await snapshot('cleaning');
  await click('.exit-battle');
  await click('[data-action="navigate"][data-value="1"]');
  await click('[data-action="begin"]');
  assert.equal(await js(`document.querySelectorAll('.memory-card').length`),6);
  await click('[data-action="flip"][data-value="0"]');
  await click('[data-action="flip"][data-value="1"]');
  await sleep(1200);
  await snapshot('memory');
  await click('.exit-battle');
  await click('[data-action="navigate"][data-value="1"]');
  await click('[data-action="begin"]');
  await sleep(1800);
  assert.equal(await js(`document.querySelectorAll('.axolotl').length`),2);
  await snapshot('patterns');
  await click('.exit-battle');
  await click('[data-action="panel"][data-value="cosmetics"]');
  for(let i=0;i<6;i++){
    await click(`[data-action="theme"][data-value="${i}"]`);
    await snapshot('theme-'+i);
  }
  await click('.drawer .close');
  await click('[data-action="panel"][data-value="settings"]');
  await submit('rename','OW browser test');
  await click('[data-action="profile"][data-value="1"]');
  assert.match(await js(`document.querySelector('footer').textContent`),/Player 2/);
  await click('[data-action="profile"][data-value="0"]');
  assert.match(await js(`document.querySelector('footer').textContent`),/OW browser test/);
  await click('[data-action="language"][data-value="fr"]');
  assert.equal(await js(`document.documentElement.lang`),'fr');
  await snapshot('settings');
  await click('.drawer .close');
  await click('[data-action="panel"][data-value="achievements"]');
  assert.equal(await js(`document.querySelectorAll('.award').length`),19);
  await snapshot('achievements');
  await click('.drawer .close');
  win.setSize(390,844);
  await snapshot('mobile');
  assert(await js(`document.querySelector('.center').getBoundingClientRect().left>=0`));
  await win.reload();await sleep(1500);
  await waitFor(`document.querySelector('footer')?.textContent.includes('OW browser test')`);
  const old=await fetch(url+'api/state').then(r=>r.json());
  let response=await fetch(url+'api/event',{method:'POST',body:JSON.stringify({action:'theme',value:'0',revision:old.revision,token:'invalid'})});
  assert.equal(response.status,403);
  response=await fetch(url+'api/event',{method:'POST',body:JSON.stringify({action:'theme',value:'0',revision:-1,token:old.token})});
  assert.equal(response.status,409);
  await fs.writeFile(path.join(ow,'generated/browser-results.json'),JSON.stringify({passed:true,snapshots},null,2));
  console.log('PASS: browser interactions, six skills, six themes, profiles, French, achievements, mobile, reload, session/revision checks.');
  win.destroy();server.kill();app.exit(0);
}).catch(async error=>{
  console.error(error);await fs.writeFile(path.join(ow,'generated/browser-results.json'),JSON.stringify({passed:false,error:String(error.stack)},null,2));
  server?.kill();app.exit(1);
});
