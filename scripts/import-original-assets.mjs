// Import the original game's assets and bestiary without npm dependencies.
// Usage: node scripts/import-original-assets.mjs C:/path/to/CodeWashGame
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
if (!process.argv[2]) throw new Error('Pass the original CodeWashGame repository directory');
const original = path.resolve(process.argv[2]);
const publicDir = path.join(original, 'public');
const manifest = [];
function copyTree(dir) {
  for (const item of fs.readdirSync(dir, { withFileTypes: true })) {
    if (item.name.startsWith('._') || item.name === '.DS_Store') continue;
    const from = path.join(dir, item.name);
    if (item.isDirectory()) copyTree(from);
    else if (item.isFile()) {
      const relative = path.relative(publicDir, from).split(path.sep).join('/');
      const to = path.join(repo, relative);
      fs.mkdirSync(path.dirname(to), { recursive: true });
      fs.copyFileSync(from, to);
      manifest.push({ path: relative, bytes: fs.statSync(from).size,
        sha256: crypto.createHash('sha256').update(fs.readFileSync(from)).digest('hex') });
    }
  }
}
copyTree(path.join(publicDir, 'assets'));
const source = fs.readFileSync(path.join(original, 'src/constants/gameData.jsx'), 'utf8');
const prefix = source.slice(0, source.indexOf('export const DIFFICULTY_CONTENT'));
const data = vm.runInNewContext(prefix.replaceAll('export const ', 'const ') +
  '\n({HOSTILE_MOBS, MINIBOSS_MOBS, BOSS_MOBS, FRIENDLY_MOBS, CHEST_BLOCKS, BASE_ASSETS})');
let ow = '# Generated by scripts/import-original-assets.mjs from the original game.\nclass OriginalAssets:\n';
for (const [method, key] of [['hostile', 'HOSTILE_MOBS'], ['mini', 'MINIBOSS_MOBS'], ['boss', 'BOSS_MOBS']]) {
  ow += `  fn ${method}():\n    return: ${JSON.stringify(Object.keys(data[key]))}\n\n`;
}
ow += '  fn image_of(name):\n';
const images = { ...data.HOSTILE_MOBS, ...data.MINIBOSS_MOBS, ...data.BOSS_MOBS,
  ...data.FRIENDLY_MOBS, ...data.CHEST_BLOCKS, ...data.BASE_ASSETS.items };
for (const [name, image] of Object.entries(images)) {
  ow += `    if: name == ${JSON.stringify(name)}\n      return: ${JSON.stringify(image.replace(/\.webp$/, '.gif'))}\n`;
}
ow += '    return: "assets/mobs/hostile/zombie.png"\n';
fs.writeFileSync(path.join(repo, 'src/OriginalAssets.ow'), ow);
fs.writeFileSync(path.join(repo, 'assets/original-manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
console.log(`Imported ${manifest.length} original assets (${manifest.reduce((n, f) => n + f.bytes, 0)} bytes).`);
console.log('For native Java image support, keep the supplied breeze.gif alongside the original breeze.webp.');
